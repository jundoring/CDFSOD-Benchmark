"""HIT-UAV exact-K-instance few-shot generation for seed2..10.

Mirrors the policy already used to build seed1
(fewshot/train_{K}shot_seed1.json, per manifest_seed1.json: "instance-exact
K-shot: exactly K annotation instances per category, DontCare excluded, 4
official classes only") and the same algorithm used for
TXL-PBC/build_txlpbc_exact_kinstance.py:
  - Sample only from the original HIT-UAV `train` split
    (normal_json/annotations_std/train.json, read-only).
  - Fixed class processing/output order: Person(0), Car(1), Bicycle(2),
    OtherVehicle(3) - matches classes.txt / existing seed1 files.
  - For K in {1,5,10}: exactly K annotations per class, images disjoint
    across classes (matches seed1's images==annotations count property).
  - Representative annotation per (class, image) = first occurrence in the
    original annotations list order.
  - random.Random(seed) reseeded per seed for reproducibility from this file
    alone.

seed1 is NEVER read, modified, or regenerated by this script - only
seed2..10 are written, following the same "seed1_preserved_untouched"
convention already used for SIXray-D's multi-seed fewshot files.
"""
import json
import os
import random

import torch
import torchvision.transforms.functional as tvF

ROOT = os.path.dirname(os.path.abspath(__file__))
TRAIN_JSON = os.path.join(ROOT, "normal_json", "annotations_std", "train.json")
OUT_DIR = os.path.join(ROOT, "fewshot")

# CD-ViTO's tools/extract_instance_prototypes.py builds a full-image-resolution
# box mask, then resizes it down to the DINOv2 patch grid
# (image resized to the nearest multiple of 14, divided by 14) and skips any
# instance whose resized mask sums to <=0.5 (i.e. the box vanishes under
# bilinear downsampling - a function of both box size AND its pixel
# alignment relative to the patch grid, not size alone: an 11x19 px box can
# vanish while a 6x11 px box elsewhere survives). For 1-shot support (K=1)
# a single such vanish makes that class disappear entirely from the
# prototype-training labels and crashes tools/run_sinkhorn_cluster.py's
# `assert num_classes == labels.max().item() + 1`. This replicates that
# exact resize computation (verified byte-for-byte against the real skip
# condition on a known failing case) so the exact-K-instance candidate pool
# never includes an instance that would trigger it, for every shot - not
# just 1-shot, so support instances always carry real training signal.


def _would_be_skipped_downstream(img_w, img_h, x, y, w, h):
    th = max(round(img_h / 14), 1) * 14
    tw = max(round(img_w / 14), 1) * 14
    target_mask_size = (th // 14, tw // 14)
    bmask = torch.zeros(1, img_h, img_w)
    x1, y1, x2, y2 = int(round(x)), int(round(y)), int(round(x + w)), int(round(y + h))
    bmask[0, y1:y2, x1:x2] = 1
    bmask = tvF.resize(bmask, target_mask_size)
    return bmask.sum().item() <= 0.5

SHOTS = [1, 5, 10]
SEEDS = list(range(2, 11))
CLASS_ORDER = [0, 1, 2, 3]  # Person, Car, Bicycle, OtherVehicle
CATEGORIES = [
    {"id": 0, "name": "Person"},
    {"id": 1, "name": "Car"},
    {"id": 2, "name": "Bicycle"},
    {"id": 3, "name": "OtherVehicle"},
]
MAX_SHOT = max(SHOTS)


def load_train():
    with open(TRAIN_JSON, encoding="utf-8") as f:
        return json.load(f)


def first_annotation_per_class(data):
    """class_id -> {image_id: annotation} using first occurrence per image,
    excluding any (image, annotation) pair whose box would be skipped by
    tools/extract_instance_prototypes.py's downstream mask-resize step."""
    img_by_id = {im["id"]: im for im in data["images"]}
    per_class = {c: {} for c in CLASS_ORDER}
    n_skipped = 0
    for ann in data["annotations"]:
        cls = ann["category_id"]
        img_id = ann["image_id"]
        if img_id in per_class[cls]:
            continue
        im = img_by_id[img_id]
        if _would_be_skipped_downstream(im["width"], im["height"], *ann["bbox"]):
            n_skipped += 1
            continue
        per_class[cls][img_id] = ann
    print(f"excluded {n_skipped} annotation(s) that would be skipped downstream "
          f"(bbox vanishes under DINOv2-patch-grid mask resize)")
    return per_class


def select_seed(seed, per_class):
    rng = random.Random(seed)
    used_img_ids = set()
    picks = {}
    for cls in CLASS_ORDER:
        candidates = sorted(per_class[cls].keys())
        candidates = [i for i in candidates if i not in used_img_ids]
        rng.shuffle(candidates)
        chosen = candidates[:MAX_SHOT]
        if len(chosen) < MAX_SHOT:
            raise RuntimeError(
                f"seed {seed}, class {cls}: only {len(chosen)} disjoint "
                f"candidate images available, need {MAX_SHOT}"
            )
        used_img_ids.update(chosen)
        picks[cls] = chosen
    return picks


def build_shot_json(K, picks, per_class, img_by_id):
    images, annotations = [], []
    img_id_out, ann_id_out = 0, 0
    for cls in CLASS_ORDER:
        for orig_img_id in picks[cls][:K]:
            im = img_by_id[orig_img_id]
            images.append({
                "id": img_id_out,
                "file_name": im["file_name"],
                "width": im["width"],
                "height": im["height"],
            })
            ann = per_class[cls][orig_img_id]
            annotations.append({
                "id": ann_id_out,
                "image_id": img_id_out,
                "category_id": cls,
                "bbox": list(ann["bbox"]),
                "area": ann["area"],
                "iscrowd": 0,
            })
            img_id_out += 1
            ann_id_out += 1
    return {"images": images, "annotations": annotations, "categories": CATEGORIES}


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    data = load_train()
    img_by_id = {im["id"]: im for im in data["images"]}
    per_class = first_annotation_per_class(data)

    for cls in CLASS_ORDER:
        print(f"class {cls} ({CATEGORIES[cls]['name']}): "
              f"{len(per_class[cls])} candidate train images")

    for seed in SEEDS:
        picks = select_seed(seed, per_class)
        for K in SHOTS:
            out = build_shot_json(K, picks, per_class, img_by_id)
            out_path = os.path.join(OUT_DIR, f"train_{K}shot_seed{seed}.json")
            with open(out_path, "w", encoding="utf-8") as f:
                json.dump(out, f, ensure_ascii=False)
            n_img, n_ann = len(out["images"]), len(out["annotations"])
            print(f"seed {seed}, {K}-shot: {n_img} images, {n_ann} annotations -> {out_path}")
            assert n_img == 4 * K and n_ann == 4 * K


if __name__ == "__main__":
    main()
